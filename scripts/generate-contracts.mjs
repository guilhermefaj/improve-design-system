import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import process from 'node:process';

const root = resolve(import.meta.dirname, '..');
const checkOnly = process.argv.includes('--check');
const tokenFiles = [
  'src/tokens/primitive.tokens.json',
  'src/tokens/semantic.tokens.json',
  'src/tokens/component.tokens.json',
];
const darkTokenFile = 'src/tokens/dark.tokens.json';

async function readJson(file) {
  return JSON.parse(await readFile(resolve(root, file), 'utf8'));
}

function flatten(node, path = [], inheritedType, result = new Map()) {
  if (!node || typeof node !== 'object' || Array.isArray(node)) return result;
  const currentType = node.$type ?? inheritedType;
  if (Object.hasOwn(node, '$value')) {
    result.set(path.join('.'), { type: currentType, value: node.$value });
    return result;
  }
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    flatten(value, [...path, key], currentType, result);
  }
  return result;
}

function resolveTokenValue(path, tokens, stack = []) {
  if (stack.includes(path)) throw new Error(`Circular token reference: ${[...stack, path].join(' -> ')}`);
  const token = tokens.get(path);
  if (!token) throw new Error(`Unknown token reference: {${path}}`);
  if (typeof token.value === 'string') {
    const exact = token.value.match(/^\{([^}]+)\}$/);
    if (exact) return resolveTokenValue(exact[1], tokens, [...stack, path]);
    return token.value.replace(/\{([^}]+)\}/g, (_, reference) =>
      formatCssValue(resolveTokenValue(reference, tokens, [...stack, path])),
    );
  }
  return token.value;
}

function formatCssValue(value) {
  if (value && typeof value === 'object' && 'value' in value && 'unit' in value) return `${value.value}${value.unit}`;
  return String(value);
}

function formatCssTokenValue(value) {
  if (typeof value !== 'string') return formatCssValue(value);
  const exact = value.match(/^\{([^}]+)\}$/);
  if (exact) return `var(${cssName(exact[1])})`;
  return value.replace(/\{([^}]+)\}/g, (_, reference) => `var(${cssName(reference)})`);
}

function cssName(path) {
  if (path === 'layout.container') return '--ibs-container';
  if (path === 'layout.content') return '--ibs-content';
  if (/^color\.(orange|purple|neutral|green|blue|red|yellow)\./.test(path))
    return `--ibs-${path.replace(/^color\./, '').replaceAll('.', '-')}`;
  return `--ibs-${path.replaceAll('.', '-')}`;
}

function toNested(resolvedEntries) {
  const output = {};
  for (const [path, value] of resolvedEntries) {
    const keys = path.split('.');
    let cursor = output;
    keys.forEach((key, index) => {
      if (index === keys.length - 1) cursor[key] = value;
      else cursor = cursor[key] ??= {};
    });
  }
  return output;
}

function buildCss(lightTokens, darkTokens) {
  const lightLines = [...lightTokens.entries()].map(
    ([path, token]) => `  ${cssName(path)}: ${formatCssTokenValue(token.value)};`,
  );
  const combined = new Map(lightTokens);
  for (const [path, token] of darkTokens) combined.set(path, token);
  const darkAliases = [...lightTokens.entries()]
    .filter(([path, token]) => !darkTokens.has(path) && typeof token.value === 'string' && token.value.includes('{'))
    .map(([path, token]) => `  ${cssName(path)}: ${formatCssTokenValue(token.value)};`);
  const darkLines = [
    ...[...darkTokens.entries()].map(([path, token]) => `  ${cssName(path)}: ${formatCssTokenValue(token.value)};`),
    ...darkAliases,
  ];
  return `/* Generated by scripts/generate-contracts.mjs. Do not edit directly. */\n:root,\n[data-ibs-theme='light'] {\n  color-scheme: light;\n${lightLines.join('\n')}\n}\n\n[data-ibs-theme='dark'] {\n  color-scheme: dark;\n${darkLines.join('\n')}\n}\n`;
}

function buildTypeScript(lightTokens, darkOverrides) {
  const combined = new Map(lightTokens);
  for (const [path, token] of darkOverrides) combined.set(path, token);
  const lightEntries = [...lightTokens.keys()].map((path) => [path, resolveTokenValue(path, lightTokens)]);
  const darkEntries = [...lightTokens.keys()].map((path) => [path, resolveTokenValue(path, combined)]);
  const lightNested = toNested(lightEntries);
  const darkNested = toNested(darkEntries);
  const flat = Object.fromEntries(lightEntries);
  const darkFlat = Object.fromEntries(darkEntries);
  const catalog = [...lightTokens.entries()].map(([path, token]) => ({
    path,
    type: token.type,
    reference: token.value,
    light: flat[path],
    dark: darkFlat[path],
  }));
  return `/* Generated by scripts/generate-contracts.mjs. Do not edit directly. */\nexport const designTokens = ${JSON.stringify(lightNested, null, 2)} as const;\n\nexport const darkDesignTokens = ${JSON.stringify(darkNested, null, 2)} as const;\n\nexport const flatTokens = ${JSON.stringify(flat, null, 2)} as const;\n\nexport const darkFlatTokens = ${JSON.stringify(darkFlat, null, 2)} as const;\n\nexport const tokenCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n\nexport type DesignTokenPath = keyof typeof flatTokens;\nexport type ThemeName = 'light' | 'dark';\n`;
}

function buildLlms(manifest, recipes, full = false) {
  const lines = [
    '# Improve Design System',
    '',
    'React/TypeScript design system for Improve Business. Canonical contract: design-system.manifest.json plus DTCG token files.',
    '',
    '## Non-negotiable brand rules',
    '- Use Inter for body copy, controls and product UI.',
    '- Use Clash Display Bold for H1, H2 and selected display highlights; fall back to Inter when its local file is unavailable.',
    '- Use Edu NSW ACT Cursive for rare expressive accents and Montserrat Medium only as a legacy supporting face.',
    '- Use white canvas, cream #F5F2F0 surfaces, dark gray #4F4F51 text, orange #F2703E as the primary brand action and purple #483C8F strategically.',
    '- Primary actions use #F2703E with bold white text by explicit brand decision; note that this pair is a documented WCAG contrast exception.',
    '- Use orange for primary actions and checked choice controls. Use purple for focus, navigation, links, human approval and agent-thinking states.',
    `- Group components by category (action, form, feedback, navigation, overlay, agentic, trust, saas, etc.) instead of atomic levels.`,
    '- Prefer generous whitespace, strong editorial hierarchy, subtle borders and restrained elevation.',
    '- Use existing components and semantic tokens before inventing new values.',
    '',
    '## Entry points',
    '- Human guide: README.md',
    '- Consumer playbook: docs/USO_EM_PROJETOS.md',
    '- Machine manifest: design-system.manifest.json',
    '- Tokens: src/tokens/*.tokens.json',
    '- Recipes: recipes/*.json',
    '- Agent skill: skills/improve-design-system/SKILL.md',
    '- Source-owned CLI: packages/cli/improve.mjs',
    '',
    '## Components',
  ];
  for (const component of manifest.components) {
    lines.push(
      `- ${component.name} (${component.id}, ${component.category}, ${component.status}): ${component.description}`,
    );
    if (full) {
      lines.push(`  Exports: ${component.exports.join(', ')}`);
      lines.push(`  States: ${component.states.join(', ') || 'none'}`);
      lines.push(`  Accessibility: ${component.accessibility.join(' ')}`);
    }
  }
  lines.push('', '## Recipes');
  for (const recipe of recipes) {
    lines.push(`- ${recipe.label} (${recipe.id}): ${recipe.purpose}`);
    if (full) {
      lines.push(`  Structure: ${recipe.structure.join(' > ')}`);
      lines.push(`  Avoid: ${recipe.antiPatterns.join(' ')}`);
    }
  }
  if (full) {
    lines.push(
      '',
      '## Agentic contract',
      'Use AgentRunStatus = queued | thinking | running | awaiting_approval | paused | succeeded | failed | cancelled. Keep SDK adapters outside the core.',
    );
  }
  return `${lines.join('\n')}\n`;
}

function buildVersionedReadme(source, version) {
  return source.replace(/#v\d+\.\d+\.\d+/g, `#v${version}`);
}

async function syncPackageVersion(file, version) {
  const pkg = await readJson(file);
  const content = `${JSON.stringify({ ...pkg, version }, null, 2)}\n`;
  await emit(file, content);
}

async function emit(file, content) {
  const target = resolve(root, file);
  if (checkOnly) {
    const existing = await readFile(target, 'utf8').catch(() => '');
    if (existing !== content) throw new Error(`Generated file is stale: ${file}. Run npm run generate.`);
    return;
  }
  await writeFile(target, content, 'utf8');
}

const lightTokens = new Map();
for (const file of tokenFiles) flatten(await readJson(file), [], undefined, lightTokens);
const darkTokens = flatten(await readJson(darkTokenFile));
for (const path of lightTokens.keys()) resolveTokenValue(path, lightTokens);

const manifest = await readJson('design-system.manifest.json');
const recipes = await Promise.all(manifest.recipes.map((recipe) => readJson(recipe.file)));
const readme = await readFile(resolve(root, 'README.md'), 'utf8');

await emit('src/styles/tokens.css', buildCss(lightTokens, darkTokens));
await emit('src/tokens/generated.ts', buildTypeScript(lightTokens, darkTokens));
await emit('llms.txt', buildLlms(manifest, recipes, false));
await emit('llms-full.txt', buildLlms(manifest, recipes, true));
await emit('README.md', buildVersionedReadme(readme, manifest.version));
for (const packageFile of [
  'package.json',
  'packages/cli/package.json',
  'packages/registry/package.json',
  'packages/artifact-kit/package.json',
]) {
  await syncPackageVersion(packageFile, manifest.version);
}

console.log(checkOnly ? 'Generated contracts are current.' : 'Generated CSS, TypeScript and LLM documentation.');
